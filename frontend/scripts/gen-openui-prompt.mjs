// Regenerates the OpenUI Lang system-prompt fragment used by the backend.
//
// The OpenUI component library (and therefore the prompt describing its
// component signatures) lives in @openuidev/react-ui on the frontend. The
// backend builds the agent system prompt but must not import a browser UI lib
// at runtime, so we generate the prompt text here and emit it as a committed
// backend source constant.
//
// Run from the frontend dir after upgrading @openuidev/*:
//   node scripts/gen-openui-prompt.mjs
//
// We strip OpenUI's default intro paragraph ("Your ENTIRE response must be
// valid openui-lang ... no markdown") because in Operator Chat the model emits
// openui-lang *inside* a ```ui fence within an otherwise normal prose reply.
// ReActAgent supplies its own framing around this fragment.

import { openuiLibrary, openuiPromptOptions } from '@openuidev/react-ui';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Use the library's own canonical prompt generator. It emits the COMPLETE
// official OpenUI Lang prompt — every component signature plus the "## Examples"
// and "## Important Rules" sections that teach correct usage (e.g. Stack with a
// "row"/"column" direction rather than inventing Row/Column). Passing
// openuiPromptOptions includes OpenUI's curated examples and additional rules.
// (generatePrompt(library.toSpec(...)) drops examples — do not use it here.)
const full = openuiLibrary.prompt(openuiPromptOptions);

// Keep everything from the first "## Syntax Rules" header onward, dropping the
// standalone-response intro that contradicts our fenced-block usage.
const start = full.indexOf('## Syntax Rules');
const body = start >= 0 ? full.slice(start).trimEnd() : full.trimEnd();

const out = `// AUTO-GENERATED by frontend/scripts/gen-openui-prompt.mjs — do not edit by hand.
// Describes OpenUI Lang syntax and the @openuidev/react-ui component library.
// Regenerate after upgrading @openuidev/* packages.

export const OPENUI_LANG_PROMPT = ${JSON.stringify(body)};
`;

const dest = path.resolve(__dirname, '../../backend/src/agent/openuiLangPrompt.ts');
fs.writeFileSync(dest, out);
console.log(`Wrote ${body.length} chars of OpenUI Lang prompt to ${dest}`);
